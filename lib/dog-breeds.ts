/** 犬種の暑さへの弱さ（0〜2）。未知・未設定は 0（標準）として扱う */
export function breedHeatSensitivity(breed: string | null | undefined): number {
  const b = breed?.trim()
  if (!b) return 0
  if (HEAT_SENSITIVE_STRONG.includes(b)) return 2
  if (HEAT_SENSITIVE_MILD.includes(b)) return 1
  return 0
}
